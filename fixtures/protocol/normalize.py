#!/usr/bin/env python3
"""Turns a proxy.py JSONL log into anonymised, replayable HTTP transcripts.

usage: normalize.py IN.jsonl OUT_DIR PROXY_PORT DESCRIPTION CLIENT_VERSION SERVER_VERSION COMMAND

OUT_DIR/NNN-request.http and NNN-response.http hold one HTTP/1.1 message each: start line,
headers, an empty line, then the exact body bytes (Content-Length matches the body; no chunking,
no content coding). OUT_DIR/session.txt lists the exchanges.
"""
import base64
import json
import os
import re
import sys

src, out, port, desc, client_ver, server_ver, command = sys.argv[1:8]
FIXED_HTTP_DATE = "Mon, 01 Jan 2024 00:00:00 GMT"
FIXED_ISO_DATE = b"2024-01-02T00:00:00.000000Z"
ORIGIN = f"127.0.0.1:{port}".encode()
DROP_REQ = {"authorization", "proxy-authorization", "cookie", "connection", "keep-alive",
            "proxy-connection", "transfer-encoding", "content-length"}
DROP_RESP = {"set-cookie", "connection", "keep-alive", "transfer-encoding", "content-length",
             "content-encoding"}
ISO = re.compile(rb"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?Z")


def scrub(data: bytes) -> bytes:
    data = data.replace(ORIGIN, b"svn.test.local")
    # Pinned repository dates are 2024-01-01T<rev>:00:00; anything else is commit/lock time.
    return ISO.sub(lambda m: m.group(0) if m.group(0).startswith(b"2024-01-01T") else FIXED_ISO_DATE, data)


def header_lines(headers, drop, response):
    lines = []
    for k, v in headers:
        lk = k.lower()
        if lk in drop:
            continue
        if lk == "host":
            v = "svn.test.local"
        elif response and lk == "date":
            v = FIXED_HTTP_DATE
        elif response and lk == "server":
            v = "Apache"
        v = scrub(v.encode("latin-1")).decode("latin-1")
        lines.append(f"{k}: {v}")
    return lines


def message(start, headers, body, response):
    head = [start] + headers + ([f"Content-Length: {len(body)}"] if body or response else [])
    return ("\r\n".join(head) + "\r\n\r\n").encode("latin-1") + body


os.makedirs(out, exist_ok=True)
rows = []
with open(src, encoding="utf-8") as f:
    records = [json.loads(line) for line in f if line.strip()]
for n, r in enumerate(sorted(records, key=lambda r: r["seq"]), start=1):
    path = scrub(r["path"].encode()).decode()
    req_body = scrub(base64.b64decode(r["req_body"]))
    resp_body = scrub(base64.b64decode(r["resp_body"]))
    req = message(f"{r['method']} {path} HTTP/1.1",
                  header_lines(r["req_headers"], DROP_REQ, False), req_body, False)
    resp = message(f"HTTP/1.1 {r['status']} {r['reason']}",
                   header_lines(r["resp_headers"], DROP_RESP, True), resp_body, True)
    with open(os.path.join(out, f"{n:03}-request.http"), "wb") as fh:
        fh.write(req)
    with open(os.path.join(out, f"{n:03}-response.http"), "wb") as fh:
        fh.write(resp)
    rows.append(f"{n:03} {r['method']} {path} -> {r['status']}")

command = re.sub(r"--password \S+", "--password ***", command).replace(ORIGIN.decode(), "svn.test.local")
command = re.sub(r"/tmp/tmp\.[A-Za-z0-9]+/", "$WORK/", command)
with open(os.path.join(out, "session.txt"), "w", encoding="utf-8") as fh:
    fh.write(f"# {desc}\n# client: svn {client_ver}\n# server: {server_ver}\n# command: {command}\n")
    fh.write("# generated by fixtures/protocol/capture.sh; one line per exchange\n")
    fh.write("\n".join(rows) + "\n")
