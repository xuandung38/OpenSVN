fn svn(o: &Oracle, cwd: &Path, args: &[&str]) -> Result<String, String> {
    let out = o
        .svn()
        .args(args)
        .current_dir(cwd)
        .output()
        .map_err(|e| e.to_string())?;
    if out.status.success() {
        Ok(String::from_utf8_lossy(&out.stdout).into_owned())
    } else {
        Err(format!(
            "svn {args:?}: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

fn lock_owner() -> LockOwner {
    LockOwner {
        store: Arc::new(MemoryLockOwnership::for_current_process("test-boot")),
        pid: std::process::id(),
        boot_id: "test-boot".to_owned(),
    }
}

fn open_wc(wc: &Path) -> WcDb {
    let db = WcDb::open(&find_wcroot(wc).expect("wc root")).expect("open wc.db");
    db.set_lock_owner(lock_owner());
    db
}

fn write_file(path: &Path, text: &str) -> Result<(), String> {
    if let Some(p) = path.parent() {
        std::fs::create_dir_all(p).map_err(|e| e.to_string())?;
    }
    std::fs::write(path, text).map_err(|e| e.to_string())
}

/// Runs `a` on our working copy through `svn_client::local`.
fn apply_ours(wc: &Path, a: &Action) -> Result<(), String> {
    let db = open_wc(wc);
    let cancel = CancelToken::new();
    let rel = |p: &str| RelPath::new(p).expect("relpath");
    let add = |p: &str| {
        local::add(
            &db,
            &cancel,
            &[wc.join(p)],
            &AddOptions::default(),
            &AddConfig::default(),
        )
        .map(|_| ())
    };
    let r = match a {
        Action::Write { path, text } => return write_file(&wc.join(path), text),
        Action::PropSet { path, name, value } => local::propset(
            &db,
            &cancel,
            &rel(path),
            name,
            Some(value.as_bytes()),
            PropSetOptions::default(),
        ),
        Action::PropDel { path, name } => local::propset(
            &db,
            &cancel,
            &rel(path),
            name,
            None,
            PropSetOptions::default(),
        ),
        Action::AddFile { path, text } => {
            write_file(&wc.join(path), text)?;
            add(path)
        }
        Action::AddDir { path, file } => {
            std::fs::create_dir(wc.join(path)).map_err(|e| e.to_string())?;
            if let Some((p, text)) = file {
                write_file(&wc.join(p), text)?;
            }
            add(path)
        }
        Action::UnversionedFile { path, text } => return write_file(&wc.join(path), text),
        Action::UnversionedDir {
            path,
            file: (p, text),
        } => {
            std::fs::create_dir(wc.join(path)).map_err(|e| e.to_string())?;
            return write_file(&wc.join(p), text);
        }
        Action::Delete { path } => local::delete(
            &db,
            &cancel,
            &[wc.join(path)],
            &DeleteOptions {
                force: true,
                ..DeleteOptions::default()
            },
        ),
        Action::Move { from, to } => {
            local::move_path(&db, &cancel, &wc.join(from), &wc.join(to)).map(|_| ())
        }
    };
    r.map_err(|e| format!("ours: {a:?}: {e}"))
}

/// Runs `a` on an svn working copy with the svn command line.
fn apply_svn(o: &Oracle, wc: &Path, a: &Action) -> Result<(), String> {
    match a {
        Action::Write { path, text } => write_file(&wc.join(path), text),
        Action::PropSet { path, name, value } => {
            svn(o, wc, &["propset", "-q", name, value, path]).map(drop)
        }
        Action::PropDel { path, name } => svn(o, wc, &["propdel", "-q", name, path]).map(drop),
        Action::AddFile { path, text } => {
            write_file(&wc.join(path), text)?;
            svn(o, wc, &["add", "-q", path]).map(drop)
        }
        Action::AddDir { path, file } => {
            std::fs::create_dir(wc.join(path)).map_err(|e| e.to_string())?;
            if let Some((p, text)) = file {
                write_file(&wc.join(p), text)?;
            }
            svn(o, wc, &["add", "-q", path]).map(drop)
        }
        Action::UnversionedFile { path, text } => write_file(&wc.join(path), text),
        Action::UnversionedDir {
            path,
            file: (p, text),
        } => {
            std::fs::create_dir(wc.join(path)).map_err(|e| e.to_string())?;
            write_file(&wc.join(p), text)
        }
        Action::Delete { path } => svn(o, wc, &["rm", "-q", "--force", path]).map(drop),
        Action::Move { from, to } => svn(o, wc, &["mv", "-q", from, to]).map(drop),
    }
    .map_err(|e| format!("svn: {a:?}: {e}"))
}

