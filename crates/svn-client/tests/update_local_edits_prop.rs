fn env_u64(name: &str) -> Option<u64> {
    let v = std::env::var(name).ok()?;
    let v = v.trim();
    let parsed = match v.strip_prefix("0x") {
        Some(hex) => u64::from_str_radix(hex, 16),
        None => v.parse(),
    };
    Some(parsed.unwrap_or_else(|e| panic!("{name}={v:?}: {e}")))
}

#[test]
fn update_over_random_local_edits_loses_nothing_and_matches_svn() {
    let oracle = common::oracle::oracle();
    let cases = env_u64("OPENSVN_PROPTEST_CASES")
        .or_else(|| env_u64("PROPTEST_CASES"))
        .map_or(DEFAULT_CASES, |n| u32::try_from(n).expect("case count"));
    let seed = env_u64("OPENSVN_PROPTEST_SEED").unwrap_or(DEFAULT_SEED);
    let keep = std::env::var_os("OPENSVN_PROPTEST_KEEP").is_some();
    eprintln!(
        "update_local_edits_prop: {cases} cases, seed {seed:#x}, svn oracle {}",
        oracle
            .as_ref()
            .map_or("off (invariant 1 only)".to_owned(), |o| format!(
                "{:?}",
                o.version()
            ))
    );
    let config = ProptestConfig {
        cases,
        failure_persistence: None,
        max_shrink_iters: 512,
        ..ProptestConfig::default()
    };
    let mut bytes = [0u8; 32];
    bytes[..8].copy_from_slice(&seed.to_le_bytes());
    let mut runner =
        TestRunner::new_with_rng(config, TestRng::from_seed(RngAlgorithm::ChaCha, &bytes));
    let rt = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(2)
        .enable_all()
        .build()
        .expect("runtime");
    let env = Run {
        rt: &rt,
        oracle: oracle.as_ref(),
        keep,
        runs: Cell::new(0),
        conflicted: Cell::new(0),
    };
    if std::env::var_os("OPENSVN_PROPTEST_SURVEY").is_some() {
        let strat = case_strategy();
        let mut fails = 0;
        for i in 0..cases {
            let case = strat.new_tree(&mut runner).expect("gen").current();
            if let Err(e) = run_case(&env, &case) {
                fails += 1;
                eprintln!("=== failing case {i}\n{e}");
            }
        }
        eprintln!(
            "update_local_edits_prop survey: {fails} of {cases} cases failed, {} ended in a \
             conflict",
            env.conflicted.get()
        );
        assert_eq!(fails, 0, "see the failing cases above");
        return;
    }
    let result = runner.run(&case_strategy(), |case| {
        run_case(&env, &case).map_err(TestCaseError::fail)
    });
    eprintln!(
        "update_local_edits_prop: {} runs (shrinking included), {} ended in a conflict",
        env.runs.get(),
        env.conflicted.get()
    );
    if let Err(e) = result {
        panic!(
            "update over local edits failed (OPENSVN_PROPTEST_SEED={seed:#x}, \
             OPENSVN_PROPTEST_CASES={cases}); set OPENSVN_PROPTEST_KEEP=1 to keep the working \
             copies\n{e}"
        );
    }
}
