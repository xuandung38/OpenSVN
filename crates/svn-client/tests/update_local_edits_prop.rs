/// What the user has before the update and must still have after it.
struct LocalData {
    /// `(file, line)` for every line the user wrote.
    lines: Vec<(String, String)>,
    /// Locally added, moved or unversioned nodes, with `true` for directories.
    nodes: Vec<(String, bool)>,
    /// `(node, name, value)` of every locally set property still set.
    props: Vec<(String, String, String)>,
}

fn local_data(tree: &Tree) -> LocalData {
    let mut d = LocalData {
        lines: Vec::new(),
        nodes: Vec::new(),
        props: Vec::new(),
    };
    for (path, node) in tree {
        if let Kind::File(lines) = &node.kind {
            for l in lines.iter().filter(|l| l.starts_with('L')) {
                d.lines.push((path.clone(), l.clone()));
            }
        }
        if node.local_new {
            d.nodes.push((path.clone(), node.kind == Kind::Dir));
        }
        for (k, v) in node.props.iter().filter(|(_, v)| v.starts_with("lv")) {
            d.props.push((path.clone(), k.clone(), v.clone()));
        }
    }
    d
}

fn check_no_loss(wc: &Path, d: &LocalData) -> Result<(), String> {
    let files = tree_snapshot(wc);
    let mut errs = Vec::new();
    for (path, line) in &d.lines {
        let found: Vec<&String> = files
            .iter()
            .filter(|(_, (dir, text, _))| {
                !dir && String::from_utf8_lossy(text).lines().any(|l| l == line)
            })
            .map(|(p, _)| p)
            .collect();
        if found.is_empty() {
            errs.push(format!("line {line:?} of {path} is gone from the disk"));
        }
    }
    for (path, is_dir) in &d.nodes {
        match std::fs::symlink_metadata(wc.join(path)) {
            Ok(md) if md.is_dir() == *is_dir => {}
            Ok(_) => errs.push(format!("local {path} changed kind")),
            Err(_) => errs.push(format!("local {path} vanished from disk")),
        }
    }
    let prej: String = files
        .iter()
        .filter(|(p, _)| p.ends_with(".prej"))
        .map(|(_, (_, t, _))| String::from_utf8_lossy(t).into_owned())
        .collect();
    let db = open_wc(wc);
    for (path, name, value) in &d.props {
        let rel = RelPath::new(path).expect("relpath");
        let kept = local::proplist(&db, &rel)
            .is_ok_and(|ps| ps.iter().any(|(k, v)| k == name && v == value.as_bytes()));
        if !kept && !prej.contains(value.as_str()) {
            errs.push(format!(
                "property {name}={value} of {path} is neither set nor in a .prej"
            ));
        }
    }
    if errs.is_empty() {
        Ok(())
    } else {
        Err(errs.join("\n"))
    }
}

