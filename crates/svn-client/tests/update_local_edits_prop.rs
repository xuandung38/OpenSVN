#[derive(Clone, Debug, PartialEq, Eq)]
enum Kind {
    Dir,
    File(Vec<String>),
}

#[derive(Clone, Debug, PartialEq, Eq)]
struct Node {
    kind: Kind,
    props: BTreeMap<String, String>,
    /// Under version control (always true on the server).
    versioned: bool,
    /// Created by a local add, move or as an unversioned item: must survive the update.
    local_new: bool,
}

impl Node {
    fn file(lines: Vec<String>, versioned: bool, local_new: bool) -> Self {
        Self {
            kind: Kind::File(lines),
            props: BTreeMap::new(),
            versioned,
            local_new,
        }
    }

    fn dir(versioned: bool, local_new: bool) -> Self {
        Self {
            kind: Kind::Dir,
            props: BTreeMap::new(),
            versioned,
            local_new,
        }
    }
}

/// Every node but the root, by relative path.
type Tree = BTreeMap<String, Node>;

fn join(dir: &str, name: &str) -> String {
    if dir.is_empty() {
        name.to_owned()
    } else {
        format!("{dir}/{name}")
    }
}

fn is_within(path: &str, root: &str) -> bool {
    path == root || path.starts_with(&format!("{root}/"))
}

fn content(lines: &[String]) -> String {
    lines.iter().map(|l| format!("{l}\n")).collect()
}

fn pick<T: Clone>(list: &[T], i: usize) -> Option<T> {
    (!list.is_empty()).then(|| list[i % list.len()].clone())
}

fn start_tree(s: &Start) -> Tree {
    let mut tree = Tree::new();
    for d in START_DIRS {
        tree.insert(d.to_owned(), Node::dir(true, false));
    }
    for (f, n) in START_FILES.iter().zip(s.files) {
        if let Some(n) = n {
            let lines = (0..n).map(|i| format!("o:{f}:{i}")).collect();
            tree.insert((*f).to_owned(), Node::file(lines, true, false));
        }
    }
    let keys: Vec<String> = tree.keys().cloned().collect();
    for &(i, p) in &s.props {
        let k = &keys[i % keys.len()];
        tree.get_mut(k)
            .expect("node")
            .props
            .insert(PROPS[p as usize].to_owned(), "o".into());
    }
    tree
}

/// Unique line and property tokens of one side (`L`/`lv` local, `S`/`sv` server).
struct Tokens {
    line: &'static str,
    value: &'static str,
    next: usize,
}

impl Tokens {
    fn line(&mut self) -> String {
        self.next += 1;
        format!("{}{}", self.line, self.next)
    }
    fn value(&mut self) -> String {
        self.next += 1;
        format!("{}{}", self.value, self.next)
    }
}

/// A concrete edit, resolved against the model, ready to run on a working copy.
#[derive(Clone, Debug)]
enum Action {
    Write {
        path: String,
        text: String,
    },
    PropSet {
        path: String,
        name: String,
        value: String,
    },
    PropDel {
        path: String,
        name: String,
    },
    AddFile {
        path: String,
        text: String,
    },
    AddDir {
        path: String,
        file: Option<(String, String)>,
    },
    UnversionedFile {
        path: String,
        text: String,
    },
    UnversionedDir {
        path: String,
        file: (String, String),
    },
    Delete {
        path: String,
    },
    Move {
        from: String,
        to: String,
    },
}

/// Resolves `op` against `tree` (applying it to the model) or returns `None` when it has no
/// valid target. `local` selects the local rules (only versioned nodes can be targeted by
/// version-control operations).
fn resolve(tree: &mut Tree, op: &Op, local: bool, tok: &mut Tokens) -> Option<Action> {
    let versioned = |tree: &Tree| -> Vec<String> {
        tree.iter()
            .filter(|(_, n)| n.versioned)
            .map(|(k, _)| k.clone())
            .collect()
    };
    let dirs = |tree: &Tree| -> Vec<String> {
        std::iter::once(String::new())
            .chain(
                tree.iter()
                    .filter(|(_, n)| n.versioned && n.kind == Kind::Dir)
                    .map(|(k, _)| k.clone()),
            )
            .collect()
    };
    match *op {
        Op::Edit { t, at, how } => {
            let files: Vec<String> = tree
                .iter()
                .filter(|(_, n)| matches!(n.kind, Kind::File(_)))
                .map(|(k, _)| k.clone())
                .collect();
            let path = pick(&files, t)?;
            let Some(Node {
                kind: Kind::File(lines),
                ..
            }) = tree.get_mut(&path)
            else {
                unreachable!()
            };
            match how {
                1 => {
                    let i = at % (lines.len() + 1);
                    lines.insert(i, tok.line());
                }
                2 if !lines.is_empty() => {
                    let i = at % lines.len();
                    lines.remove(i);
                }
                3 if lines.len() >= 2 => {
                    let i = at % (lines.len() - 1);
                    lines[i] = tok.line();
                    lines[i + 1] = tok.line();
                }
                _ if !lines.is_empty() => {
                    let i = at % lines.len();
                    lines[i] = tok.line();
                }
                _ => lines.push(tok.line()),
            }
            Some(Action::Write {
                text: content(lines),
                path,
            })
        }
        Op::PropSet { t, name } => {
            let path = pick(&versioned(tree), t)?;
            let (name, value) = (PROPS[name as usize].to_owned(), tok.value());
            tree.get_mut(&path)?
                .props
                .insert(name.clone(), value.clone());
            Some(Action::PropSet { path, name, value })
        }
        Op::PropDel { t, name } => {
            let with_props: Vec<String> = tree
                .iter()
                .filter(|(_, n)| n.versioned && !n.props.is_empty())
                .map(|(k, _)| k.clone())
                .collect();
            let path = pick(&with_props, t)?;
            let node = tree.get_mut(&path)?;
            let names: Vec<String> = node.props.keys().cloned().collect();
            let name = pick(&names, name as usize)?;
            node.props.remove(&name);
            Some(Action::PropDel { path, name })
        }
        Op::AddFile { dir, name, lines } => {
            let path = join(&pick(&dirs(tree), dir)?, NAMES[name as usize]);
            if tree.contains_key(&path) {
                return None;
            }
            let lines: Vec<String> = (0..lines).map(|_| tok.line()).collect();
            let text = content(&lines);
            tree.insert(path.clone(), Node::file(lines, true, local));
            Some(Action::AddFile { path, text })
        }
        Op::AddDir {
            dir,
            name,
            with_file,
        } => {
            let path = join(&pick(&dirs(tree), dir)?, NAMES[name as usize]);
            if tree.contains_key(&path) {
                return None;
            }
            tree.insert(path.clone(), Node::dir(true, local));
            let file = with_file.then(|| {
                let lines = vec![tok.line(), tok.line()];
                let (p, text) = (join(&path, "h"), content(&lines));
                tree.insert(p.clone(), Node::file(lines, true, local));
                (p, text)
            });
            Some(Action::AddDir { path, file })
        }
        Op::Unversioned { dir, name, is_dir } => {
            if !local {
                let lines = 2;
                return resolve(
                    tree,
                    &if is_dir {
                        Op::AddDir {
                            dir,
                            name,
                            with_file: true,
                        }
                    } else {
                        Op::AddFile { dir, name, lines }
                    },
                    local,
                    tok,
                );
            }
            let path = join(&pick(&dirs(tree), dir)?, NAMES[name as usize]);
            if tree.contains_key(&path) {
                return None;
            }
            let lines = vec![tok.line(), tok.line()];
            let text = content(&lines);
            if is_dir {
                let p = join(&path, "h");
                tree.insert(path.clone(), Node::dir(false, true));
                tree.insert(p.clone(), Node::file(lines, false, true));
                Some(Action::UnversionedDir {
                    path,
                    file: (p, text),
                })
            } else {
                tree.insert(path.clone(), Node::file(lines, false, true));
                Some(Action::UnversionedFile { path, text })
            }
        }
        Op::Delete { t } => {
            let path = pick(&versioned(tree), t)?;
            tree.retain(|k, _| !is_within(k, &path));
            Some(Action::Delete { path })
        }
        Op::Move { t, dir, name } => {
            // `svn_client::local::move_path` cannot move a subtree holding a locally added,
            // copied or moved node yet (it refuses with "not supported yet"), so a local move
            // only takes nodes that are unchanged in structure: no chains of moves either.
            let movable: Vec<String> = versioned(tree)
                .into_iter()
                .filter(|p| {
                    !local
                        || !tree
                            .iter()
                            .any(|(k, n)| is_within(k, p) && n.versioned && n.local_new)
                })
                .collect();
            let from = pick(&movable, t)?;
            let dests: Vec<String> = dirs(tree)
                .into_iter()
                .filter(|d| !is_within(d, &from))
                .collect();
            let to = join(&pick(&dests, dir)?, NAMES[name as usize]);
            if tree.contains_key(&to) {
                return None;
            }
            let moved: Vec<(String, Node)> = tree
                .iter()
                .filter(|(k, _)| is_within(k, &from))
                .map(|(k, n)| (k.clone(), n.clone()))
                .collect();
            tree.retain(|k, _| !is_within(k, &from));
            for (k, mut n) in moved {
                n.local_new |= local && n.versioned;
                tree.insert(format!("{to}{}", &k[from.len()..]), n);
            }
            Some(Action::Move { from, to })
        }
    }
}

