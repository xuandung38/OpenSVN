//! Property test of `update` over local modifications (issue #15).
//!
//! Each generated case builds a small repository (r1: a few directories and multi-line text
//! files, some with properties), checks it out at r1, applies random *local* edits (line edits,
//! property set/delete, add file/dir, unversioned file/dir, delete, move) and commits random
//! *server* edits of the same files and directories as r2, so text, property and tree conflicts
//! and obstructions are common. Then it updates to HEAD and checks:
//!
//! 1. Always: no local data is lost. Every line the user wrote (every line of a locally edited,
//!    added or unversioned file that is not in the repository) is still somewhere in the working
//!    copy: the working file, `.mine`, the merged file with markers or any other file kept on
//!    disk. Every locally added or unversioned file and directory still exists with the same kind,
//!    and every locally set property value is still a working property of its node or appears
//!    in a `.prej` file.
//! 2. With svn 1.15 (`OPENSVN_SVN_BIN`, `OPENSVN_SVNADMIN_BIN`; `OPENSVN_REQUIRE_SVN=1` makes it
//!    mandatory): the repository is made by svn and replayed into the fake session
//!    (`common::oracle`), the same local edits are made with the svn command line in a real
//!    `svn checkout` (and through `svn_client::local` in ours), and after `svn update --accept postpone` both working copies must have the
//!    same files on disk, the same NODES and ACTUAL rows (`nodes_snapshot`/`actual_snapshot`)
//!    and the same `svn status`. The two copies are compared before the update too, so a
//!    difference made by a local operation is not blamed on the update.
//!
//! Cases are generated by proptest from a fixed seed and shrink on failure. Environment:
//! - `OPENSVN_PROPTEST_CASES` (then `PROPTEST_CASES`): number of cases, default 32;
//! - `OPENSVN_PROPTEST_SEED`: RNG seed (decimal or `0x` hex), default [`DEFAULT_SEED`];
//! - `OPENSVN_PROPTEST_KEEP=1`: keep the working copies of a failing case on disk;
//! - `OPENSVN_PROPTEST_SURVEY=1`: run every case without stopping or shrinking and print each
//!   failure (to see all kinds of failure at once when triaging).
//!
//! Left out on purpose: local moves of subtrees holding locally added or moved nodes (the
//! client refuses them, see `resolve`), and svn's tracking of local moves during an update,
//! which our update lacks (see `nodes_without_move_bump`), and one effect of the fake
//! session's drive order (see `ours_with_broken_moves`).
#![allow(clippy::expect_used, clippy::unwrap_used, clippy::panic)]

