/// Seed used when `OPENSVN_PROPTEST_SEED` is unset.
const DEFAULT_SEED: u64 = 0x15_0b5e_ed15;
/// Cases used when neither `OPENSVN_PROPTEST_CASES` nor `PROPTEST_CASES` is set.
const DEFAULT_CASES: u32 = 32;

/// Names new nodes get. `f` and `h` are also names of r1 files, so adds and moves collide with
/// existing (or locally deleted, then replaced) nodes.
const NAMES: [&str; 4] = ["n1", "n2", "f", "h"];
/// Property names; `p1` is also used for r1 properties.
const PROPS: [&str; 2] = ["p1", "p2"];
/// r1 always has these directories ...
const START_DIRS: [&str; 3] = ["A", "A/B", "C"];
/// ... and a subset of these files.
const START_FILES: [&str; 5] = ["A/f", "A/g", "A/B/h", "C/k", "top"];

