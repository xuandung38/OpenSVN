/// One abstract edit. Targets are indices taken modulo the list of nodes the edit can apply to
/// at the moment it runs, so every op stays meaningful while proptest shrinks the others away.
#[derive(Clone, Debug)]
enum Op {
    /// `how`: 0 replace a line, 1 insert a line, 2 delete a line, 3 replace two lines.
    Edit {
        t: usize,
        at: usize,
        how: u8,
    },
    PropSet {
        t: usize,
        name: u8,
    },
    PropDel {
        t: usize,
        name: u8,
    },
    AddFile {
        dir: usize,
        name: u8,
        lines: u8,
    },
    AddDir {
        dir: usize,
        name: u8,
        with_file: bool,
    },
    /// Local: an unversioned file or directory left on disk. Server: an ordinary add.
    Unversioned {
        dir: usize,
        name: u8,
        is_dir: bool,
    },
    Delete {
        t: usize,
    },
    /// Local: `svn mv`. Server: delete plus add without history (the dump replay has no copies).
    Move {
        t: usize,
        dir: usize,
        name: u8,
    },
}

#[derive(Clone, Debug)]
struct Start {
    /// Present files of [`START_FILES`] with their line count.
    files: [Option<u8>; 5],
    /// `(node index, property index)` set in r1, value `o`.
    props: Vec<(usize, u8)>,
}

#[derive(Clone, Debug)]
struct Case {
    start: Start,
    local: Vec<Op>,
    server: Vec<Op>,
}

fn op_strategy() -> impl Strategy<Value = Op> {
    let t = 0usize..64;
    let name = 0u8..NAMES.len() as u8;
    prop_oneof![
        6 => (t.clone(), 0usize..16, 0u8..4).prop_map(|(t, at, how)| Op::Edit { t, at, how }),
        2 => (t.clone(), 0u8..PROPS.len() as u8).prop_map(|(t, name)| Op::PropSet { t, name }),
        1 => (t.clone(), 0u8..4).prop_map(|(t, name)| Op::PropDel { t, name }),
        2 => (t.clone(), name.clone(), 1u8..4)
            .prop_map(|(dir, name, lines)| Op::AddFile { dir, name, lines }),
        1 => (t.clone(), name.clone(), any::<bool>())
            .prop_map(|(dir, name, with_file)| Op::AddDir { dir, name, with_file }),
        1 => (t.clone(), name.clone(), any::<bool>())
            .prop_map(|(dir, name, is_dir)| Op::Unversioned { dir, name, is_dir }),
        2 => t.clone().prop_map(|t| Op::Delete { t }),
        2 => (t.clone(), t, name).prop_map(|(t, dir, name)| Op::Move { t, dir, name }),
    ]
}

fn case_strategy() -> impl Strategy<Value = Case> {
    let start = (
        proptest::array::uniform5(proptest::option::weighted(0.8, 2u8..8)),
        proptest::collection::vec((0usize..8, 0u8..PROPS.len() as u8), 0..3),
    )
        .prop_map(|(files, props)| Start { files, props });
    (
        start,
        proptest::collection::vec(op_strategy(), 1..8),
        proptest::collection::vec(op_strategy(), 1..6),
    )
        .prop_map(|(start, local, server)| Case {
            start,
            local,
            server,
        })
}

