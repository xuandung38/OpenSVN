struct Run<'a> {
    rt: &'a tokio::runtime::Runtime,
    oracle: Option<&'a Oracle>,
    keep: bool,
    /// Cases run, and how many of them ended with at least one conflict in our working copy.
    runs: Cell<u32>,
    conflicted: Cell<u32>,
}

/// Runs one case; the error names the concrete actions and what went wrong.
fn run_case(env: &Run<'_>, case: &Case) -> Result<(), String> {
    let r1 = start_tree(&case.start);
    let mut r2 = r1.clone();
    let mut server_tok = Tokens {
        line: "S",
        value: "sv",
        next: 0,
    };
    let server: Vec<Action> = case
        .server
        .iter()
        .filter_map(|op| resolve(&mut r2, op, false, &mut server_tok))
        .collect();
    let mut model = r1.clone();
    let mut local_tok = Tokens {
        line: "L",
        value: "lv",
        next: 0,
    };
    let local: Vec<Action> = case
        .local
        .iter()
        .filter_map(|op| resolve(&mut model, op, true, &mut local_tok))
        .collect();
    let mut log = String::new();
    let _ = writeln!(log, "r1: {:?}", r1.keys().collect::<Vec<_>>());
    for a in &server {
        let _ = writeln!(log, "  server: {a:?}");
    }
    for a in &local {
        let _ = writeln!(log, "  local:  {a:?}");
    }
    let sb = tempfile::tempdir().map_err(|e| e.to_string())?;
    let base = sb.path().canonicalize().map_err(|e| e.to_string())?;
    let ours = base.join("ours");

    // Repository: made by svn and replayed when the oracle is there, seeded directly otherwise.
    let mut repo_keep = None;
    let (fake, theirs) = match env.oracle {
        Some(o) => {
            let repo = Repo::new(o);
            let seed = repo.checkout("seed");
            svn_commit(o, &seed, &Tree::new(), &r1).map_err(|e| format!("{log}r1: {e}"))?;
            if r2 != r1 {
                svn_commit(o, &seed, &r1, &r2).map_err(|e| format!("{log}r2: {e}"))?;
            }
            let fake = repo.fake(None);
            let theirs = repo.base().join("theirs");
            svn(
                o,
                &repo.base(),
                &["checkout", "-q", "-r", "1", &repo.url, "theirs"],
            )
            .map_err(|e| format!("{log}{e}"))?;
            repo_keep = Some(repo);
            (fake, Some(theirs))
        }
        None => {
            let s: FakeRaSession = common::session();
            s.seed("a", "r1", &fake_changes(&Tree::new(), &r1))
                .map_err(|e| e.to_string())?;
            if r2 != r1 {
                s.seed("a", "r2", &fake_changes(&r1, &r2))
                    .map_err(|e| e.to_string())?;
            }
            (s, None)
        }
    };
    let cancel = CancelToken::new();
    env.rt
        .block_on(checkout(
            &common::ctx(),
            &fake,
            &ours,
            Some(Revnum(1)),
            Depth::Infinity,
            false,
            &cancel,
        ))
        .map_err(|e| format!("{log}checkout: {e}"))?;

    let result = (|| -> Result<(), String> {
        for a in &local {
            if let (Some(o), Some(t)) = (env.oracle, &theirs) {
                apply_svn(o, t, a)?;
            }
            apply_ours(&ours, a)?;
        }
        if let (Some(o), Some(t)) = (env.oracle, &theirs) {
            compare_with_svn(o, t, &ours).map_err(|e| format!("before the update: {e}"))?;
        }
        let data = local_data(&model);
        check_no_loss(&ours, &data).map_err(|e| format!("model and disk disagree: {e}"))?;

        let svn_up = match (env.oracle, &theirs) {
            (Some(o), Some(t)) => Some(svn(o, t, &["update", "-q", "--accept", "postpone"])),
            _ => None,
        };
        let our_up = env.rt.block_on(update(
            &common::ctx(),
            &fake,
            &ours,
            None,
            Depth::Unknown,
            &cancel,
        ));
        env.runs.set(env.runs.get() + 1);
        if our_up.as_ref().is_ok_and(|s| !s.conflicts().is_empty()) {
            env.conflicted.set(env.conflicted.get() + 1);
        }
        let mut errs = String::new();
        if let Err(e) = check_no_loss(&ours, &data) {
            let _ = writeln!(errs, "LOCAL DATA LOST:\n{e}");
        }
        match (&svn_up, &our_up) {
            (None, Err(e)) => {
                let _ = writeln!(errs, "update failed: {e}");
            }
            (Some(Ok(_)), Err(e)) => {
                let _ = writeln!(errs, "our update failed where svn's succeeded: {e}");
            }
            (Some(Err(e)), Ok(_)) => {
                let _ = writeln!(errs, "svn update failed where ours succeeded: {e}");
            }
            _ => {}
        }
        if let (Some(o), Some(t)) = (env.oracle, &theirs)
            && let Err(e) = compare_with_svn(o, t, &ours)
        {
            let _ = write!(errs, "after the update, ours vs svn 1.15: {e}");
        }
        if errs.is_empty() { Ok(()) } else { Err(errs) }
    })();
    result.map_err(|e| {
        let mut msg = format!("{log}{e}");
        if env.keep {
            let _ = write!(msg, "\nkept: ours {}", ours.display());
            if let Some(t) = &theirs {
                let _ = write!(msg, ", svn {}", t.display());
            }
            std::mem::forget(sb);
            std::mem::forget(repo_keep);
        }
        msg
    })
}

