/// Nodes of `old` that are gone (or changed kind) in `new`, outermost first, without
/// descendants of an already listed node.
fn removed(old: &Tree, new: &Tree) -> Vec<String> {
    let gone: BTreeSet<&String> = old
        .iter()
        .filter(|(k, n)| {
            new.get(*k)
                .is_none_or(|m| (m.kind == Kind::Dir) != (n.kind == Kind::Dir))
        })
        .map(|(k, _)| k)
        .collect();
    gone.iter()
        .filter(|k| {
            !gone
                .iter()
                .any(|g| g != *k && k.starts_with(&format!("{g}/")))
        })
        .map(|k| (*k).clone())
        .collect()
}

/// `true` when `path` is new in `new` (absent from `old`, or there with another kind).
fn is_new(old: &Tree, path: &str, node: &Node) -> bool {
    old.get(path)
        .is_none_or(|o| (o.kind == Kind::Dir) != (node.kind == Kind::Dir))
}

/// Fake-session changes that turn `old` into `new`.
fn fake_changes(old: &Tree, new: &Tree) -> Vec<FakeChange> {
    let rp = |p: &str| RelPath::new(p).expect("relpath");
    let mut out: Vec<FakeChange> = removed(old, new)
        .iter()
        .map(|p| FakeChange::Delete(rp(p)))
        .collect();
    for (path, node) in new {
        let fresh = is_new(old, path, node);
        match &node.kind {
            Kind::Dir if fresh => out.push(FakeChange::PutDir(rp(path))),
            Kind::Dir => {}
            Kind::File(lines) => {
                if fresh || old.get(path).map(|o| &o.kind) != Some(&node.kind) {
                    out.push(FakeChange::PutFile(
                        rp(path),
                        Bytes::from(content(lines).into_bytes()),
                    ));
                }
            }
        }
        let before = if fresh {
            BTreeMap::new()
        } else {
            old[path].props.clone()
        };
        for (k, v) in &node.props {
            if before.get(k) != Some(v) {
                out.push(FakeChange::SetProp(
                    rp(path),
                    PropChange {
                        name: k.clone(),
                        value: Some(Bytes::from(v.clone().into_bytes())),
                    },
                ));
            }
        }
        for k in before.keys().filter(|k| !node.props.contains_key(*k)) {
            out.push(FakeChange::SetProp(
                rp(path),
                PropChange {
                    name: k.clone(),
                    value: None,
                },
            ));
        }
    }
    out
}

/// Makes the svn working copy `seed` (a checkout of `old`) look like `new` and commits it.
fn svn_commit(o: &Oracle, seed: &Path, old: &Tree, new: &Tree) -> Result<(), String> {
    svn(o, seed, &["update", "-q"])?;
    for p in removed(old, new) {
        svn(o, seed, &["rm", "-q", "--force", &p])?;
    }
    for (path, node) in new {
        let fresh = is_new(old, path, node);
        match &node.kind {
            Kind::Dir if fresh => {
                std::fs::create_dir(seed.join(path)).map_err(|e| e.to_string())?;
                svn(o, seed, &["add", "-q", "--depth", "empty", path])?;
            }
            Kind::Dir => {}
            Kind::File(lines) => {
                std::fs::write(seed.join(path), content(lines)).map_err(|e| e.to_string())?;
                if fresh {
                    svn(o, seed, &["add", "-q", path])?;
                }
            }
        }
        let before = if fresh {
            BTreeMap::new()
        } else {
            old[path].props.clone()
        };
        for (k, v) in &node.props {
            if before.get(k) != Some(v) {
                svn(o, seed, &["propset", "-q", k, v, path])?;
            }
        }
        for k in before.keys().filter(|k| !node.props.contains_key(*k)) {
            svn(o, seed, &["propdel", "-q", k, path])?;
        }
    }
    svn(o, seed, &["commit", "-q", "-m", "r"])?;
    Ok(())
}

