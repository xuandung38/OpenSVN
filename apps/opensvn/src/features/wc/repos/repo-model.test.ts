import { expect, test } from "vitest";
import ranges from "./deceptive-ranges.json";
import { FORMAT_CHARS, validateFolderName } from "./repo-model";

/** C0 and C1 controls: refused by their own rule, not part of the fixture. */
const isControl = (cp: number) => cp <= 0x1f || (cp >= 0x7f && cp <= 0x9f);

test("FORMAT_CHARS is exactly the backend's is_deceptive set (fixture generated by a Rust test)", () => {
  const want = new Set<number>();
  for (const [first, last] of ranges as [number, number][]) {
    for (let cp = first; cp <= last; cp++) want.add(cp);
  }
  expect(want.has(0x0890) && want.has(0x0891)).toBe(true);
  const wrong: string[] = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue; // not a Rust `char`
    if (isControl(cp)) continue;
    if (FORMAT_CHARS.test(String.fromCodePoint(cp)) !== want.has(cp)) {
      wrong.push(`U+${cp.toString(16).toUpperCase().padStart(4, "0")}`);
    }
  }
  expect(wrong).toEqual([]);
  expect(validateFolderName("a࢐b")).toBe("format");
  expect(validateFolderName("a࢑b")).toBe("format");
});
