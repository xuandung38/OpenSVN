#!/usr/bin/env bash
# Evil server without Docker: Apache httpd + mod_dav_svn over HTTPS (Basic auth tester /
# tester-pass, throwaway CA) serving the hostile repository of fixtures/evil/make-hostile-repo.sh
# at https://localhost:$EVIL_PORT/svn/hostile. The Dockerfile next to this script runs the same
# script in the foreground.
#
#   docker/evil-server/run-local.sh up       # build the repository, certificates, start httpd
#   docker/evil-server/run-local.sh env      # print the variables the tests read
#   docker/evil-server/run-local.sh down     # stop httpd (keeps the state directory)
#   docker/evil-server/run-local.sh purge    # down + delete the state directory
#   docker/evil-server/run-local.sh foreground   # up, but httpd stays in the foreground
#
# Env: EVIL_DIR      state directory (default /tmp/opensvn-evil-server)
#      EVIL_PORT     HTTPS port on 127.0.0.1 (default 18543)
#      BEACON        URL prefix of every network beacon in the repository (see the builder)
#      HTTPD         httpd binary (default: apache2 or httpd from PATH or /usr/sbin)
#      APACHE_MODULES  directory with mod_ssl.so etc. (default: Debian/Ubuntu or RHEL layout)
#      MOD_DAV_SVN   mod_dav_svn.so (default: $APACHE_MODULES/mod_dav_svn.so)
# Needs: Apache 2.4 with mod_ssl, mod_dav, mod_dav_svn (Debian/Ubuntu: apache2
#        libapache2-mod-svn), openssl, svn/svnadmin/svnmucc and python3 for the builder.
# Test-only credentials and keys; never reuse them.
set -euo pipefail
export LANG=C.UTF-8 LC_ALL=C.UTF-8
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
root="$(cd "$here/../.." && pwd)"
EVIL_DIR="${EVIL_DIR:-/tmp/opensvn-evil-server}"
EVIL_PORT="${EVIL_PORT:-18543}"
USER_NAME=tester
USER_PASS=tester-pass

die() { echo "evil-server: $*" >&2; exit 1; }

find_httpd() {
  if [ -n "${HTTPD:-}" ]; then echo "$HTTPD"; return; fi
  local c
  for c in apache2 httpd /usr/sbin/apache2 /usr/sbin/httpd; do
    if command -v "$c" >/dev/null 2>&1; then command -v "$c"; return; fi
  done
  die "no Apache httpd found (install apache2 + libapache2-mod-svn, or set HTTPD)"
}

find_modules() {
  if [ -n "${APACHE_MODULES:-}" ]; then echo "$APACHE_MODULES"; return; fi
  local d
  for d in /usr/lib/apache2/modules /usr/lib64/httpd/modules /usr/lib/httpd/modules \
    /usr/libexec/apache2; do
    [ -f "$d/mod_ssl.so" ] && { echo "$d"; return; }
  done
  die "no Apache module directory with mod_ssl.so found (set APACHE_MODULES)"
}

pid_file() { echo "$EVIL_DIR/httpd.pid"; }

running() { [ -s "$(pid_file)" ] && kill -0 "$(cat "$(pid_file)")" 2>/dev/null; }

write_conf() {
  local mods="$1" dav_svn="$2" user_line=""
  # As root (container), httpd must drop privileges; the repository is chowned to that user.
  if [ "$(id -u)" = 0 ]; then
    local u=www-data
    id "$u" >/dev/null 2>&1 || u=apache
    id "$u" >/dev/null 2>&1 || u=nobody
    user_line="User $u
Group $(id -gn "$u")"
    chown -R "$u" "$EVIL_DIR/repos"
    # A mktemp state directory is 0700; httpd's user must reach the repository and htpasswd.
    chmod 755 "$EVIL_DIR"
    chmod 644 "$EVIL_DIR/htpasswd"
  fi
  cat > "$EVIL_DIR/httpd.conf" <<EOF
# Generated by docker/evil-server/run-local.sh
ServerRoot $EVIL_DIR
ServerName evil.test
PidFile $(pid_file)
DefaultRuntimeDir $EVIL_DIR/run
Mutex file:$EVIL_DIR/run default
Listen 127.0.0.1:$EVIL_PORT
$user_line
LoadModule mpm_event_module $mods/mod_mpm_event.so
LoadModule authn_core_module $mods/mod_authn_core.so
LoadModule authn_file_module $mods/mod_authn_file.so
LoadModule authz_core_module $mods/mod_authz_core.so
LoadModule authz_user_module $mods/mod_authz_user.so
LoadModule auth_basic_module $mods/mod_auth_basic.so
LoadModule dav_module $mods/mod_dav.so
LoadModule dav_svn_module $dav_svn
LoadModule socache_shmcb_module $mods/mod_socache_shmcb.so
LoadModule ssl_module $mods/mod_ssl.so
ErrorLog $EVIL_DIR/logs/error.log
LogLevel warn
LogFormat "%h %u \"%r\" %>s %O" evil
CustomLog $EVIL_DIR/logs/access.log evil
SSLEngine on
SSLCertificateFile $EVIL_DIR/certs/server.crt
SSLCertificateKeyFile $EVIL_DIR/certs/server.key
SSLProtocol -all +TLSv1.2 +TLSv1.3
SSLSessionCache shmcb:$EVIL_DIR/run/ssl_scache(512000)
<Location /svn>
  DAV svn
  SVNParentPath $EVIL_DIR/repos
  SVNListParentPath On
  SVNAdvertiseV2Protocol On
  AuthType Basic
  AuthName "OpenSVN evil server"
  AuthBasicProvider file
  AuthUserFile $EVIL_DIR/htpasswd
  Require valid-user
</Location>
EOF
}

prepare() {
  local httpd mods dav_svn
  httpd="$(find_httpd)"
  mods="$(find_modules)"
  dav_svn="${MOD_DAV_SVN:-$mods/mod_dav_svn.so}"
  [ -f "$dav_svn" ] || die "mod_dav_svn.so not found at $dav_svn (set MOD_DAV_SVN)"
  running && die "already running (pid $(cat "$(pid_file)")); run down first"
  mkdir -p "$EVIL_DIR"/{logs,run,repos}
  sh "$root/docker/svn-server/gen-certs.sh" "$EVIL_DIR/certs" >/dev/null
  # apr1 hashes are understood by every Apache 2.4 build; no apache2-utils needed.
  printf '%s:%s\n' "$USER_NAME" "$(openssl passwd -apr1 "$USER_PASS")" > "$EVIL_DIR/htpasswd"
  rm -rf "$EVIL_DIR/repos/hostile"
  bash "$root/fixtures/evil/make-hostile-repo.sh" "$EVIL_DIR/repos/hostile" >&2 \
    2> >(grep -v "is a binary mime-type" >&2)
  write_conf "$mods" "$dav_svn"
  "$httpd" -t -f "$EVIL_DIR/httpd.conf" >/dev/null 2>&1 \
    || { "$httpd" -t -f "$EVIL_DIR/httpd.conf"; die "httpd configuration test failed"; }
  echo "$httpd"
}

wait_up() {
  local i
  for i in $(seq 100); do
    if curl -fsS --cacert "$EVIL_DIR/certs/ca.crt" -u "$USER_NAME:$USER_PASS" \
      "https://localhost:$EVIL_PORT/svn/hostile/" -o /dev/null 2>/dev/null; then
      return 0
    fi
    sleep 0.1
  done
  tail -20 "$EVIL_DIR/logs/error.log" >&2 || true
  die "httpd did not answer on port $EVIL_PORT"
}

cmd_up() {
  local httpd
  httpd="$(prepare)"
  "$httpd" -f "$EVIL_DIR/httpd.conf" -k start
  wait_up
  echo "evil server: https://localhost:$EVIL_PORT/svn/hostile (CA $EVIL_DIR/certs/ca.crt)"
}

cmd_foreground() {
  local httpd
  httpd="$(prepare)"
  exec "$httpd" -f "$EVIL_DIR/httpd.conf" -DFOREGROUND
}

cmd_down() {
  if running; then
    kill "$(cat "$(pid_file)")"
    local i
    for i in $(seq 50); do running || break; sleep 0.1; done
  fi
  rm -f "$(pid_file)"
}

cmd_env() {
  cat <<EOF
export OPENSVN_EVIL_URL=https://localhost:$EVIL_PORT/svn/hostile
export OPENSVN_EVIL_CA=$EVIL_DIR/certs/ca.crt
export OPENSVN_EVIL_REPO=$EVIL_DIR/repos/hostile
EOF
}

case "${1:-}" in
  up) cmd_up ;;
  foreground) cmd_foreground ;;
  down) cmd_down ;;
  purge) cmd_down; rm -rf "$EVIL_DIR" ;;
  env) cmd_env ;;
  *) sed -n '2,25p' "$0" >&2; exit 2 ;;
esac
